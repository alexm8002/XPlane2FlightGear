#!/usr/bin/env python3
"""Experimental selective draping of ground-like AC3D triangles on TerraGear BTG.

Only supports the single OBJECT poly / numvert / numsurf format generated by
xp2fg.py. Never modifies original AC3D or BTG. Preview is the default.
"""
from __future__ import annotations
import argparse
from collections import Counter
import json
import math
from pathlib import Path
import shutil
from dataclasses import dataclass
from btg_elevation import TerrainSampler

VERSION = '0.3.10'

@dataclass
class Placement:
    stg: Path
    line_index: int
    raw: str
    keyword: str
    model: str
    lon: float
    lat: float
    altitude: float
    heading: float


def placements(root):
    found=[]
    for stg in sorted((root/'Objects').rglob('*.stg')):
        for i,line in enumerate(stg.read_text(encoding='utf-8').splitlines()):
            p=line.split()
            if len(p)>=6 and p[0] in ('OBJECT_STATIC','OBJECT_STATIC_AGL'):
                try:
                    found.append(Placement(stg,i,line,p[0],p[1],*map(float,p[2:6])))
                except ValueError: pass
    return found


def shift(lon, lat, east, north):
    phi=math.radians(lat)
    mlat=111132.92-559.82*math.cos(2*phi)+1.175*math.cos(4*phi)
    mlon=111412.84*math.cos(phi)-93.5*math.cos(3*phi)+0.118*math.cos(5*phi)
    if mlon<=1: raise ValueError('Longitude hors plage')
    return lon+east/mlon,lat+north/mlat


def vertex_geodetic(p, xyz):
    # OBJ8 -> AC3D v0.3.6: +X south, +Z west at 0 heading.
    # STG heading rotates counterclockwise about local up.
    x,y,z=xyz
    h=math.radians(p.heading)
    east=x*math.sin(h)-z*math.cos(h)
    north=-x*math.cos(h)-z*math.sin(h)
    return shift(p.lon,p.lat,east,north)


@dataclass
class Face:
    flag: str
    mat: str
    refs: list  # (index, u, v)


class AC:
    def __init__(self,path):
        self.path=Path(path)
        lines=self.path.read_text(encoding='utf8',errors='replace').splitlines()
        vpos=next((i for i,line in enumerate(lines) if line.startswith('numvert ')),None)
        if vpos is None: raise ValueError('AC3D: aucun numvert')
        n=int(lines[vpos].split()[1])
        if n>3_000_000: raise ValueError('Trop de sommets AC3D')
        self.vertices=[tuple(map(float,lines[j].split()[:3])) for j in range(vpos+1,vpos+1+n)]
        spos=vpos+1+n
        if spos>=len(lines) or not lines[spos].startswith('numsurf '):
            raise ValueError('Seulement les AC3D convertis par xp2fg sont pris en charge')
        count=int(lines[spos].split()[1])
        if count>2_000_000: raise ValueError('Trop de faces AC3D')
        self.faces=[]
        i=spos+1
        for _ in range(count):
            if not lines[i].startswith('SURF ') or not lines[i+1].startswith('mat ') or not lines[i+2].startswith('refs '):
                raise ValueError('Surface AC3D non standard; conversion refusee')
            nref=int(lines[i+2].split()[1])
            if nref!=3: raise ValueError('Faces non triangulaires non prises en charge')
            refs=[]
            for s in lines[i+3:i+6]:
                a,b,c=s.split()[:3]
                refs.append((int(a),float(b),float(c)))
            if any(j<0 or j>=n for j,_,_ in refs): raise ValueError('Indice AC3D invalide')
            self.faces.append(Face(lines[i],lines[i+1],refs))
            i+=6
        if i>=len(lines) or lines[i].strip()!='kids 0':
            raise ValueError('Modele AC3D structurellement different: pas de kids 0')
        self.prefix=lines[:vpos]
        self.suffix=lines[i:]

    def write(self,path,vertices,faces):
        path=Path(path)
        with path.open('w',encoding='utf8') as f:
            f.write('\n'.join(self.prefix)+'\n')
            f.write(f'numvert {len(vertices)}\n')
            for x,y,z in vertices:f.write(f'{x:.7f} {y:.7f} {z:.7f}\n')
            f.write(f'numsurf {len(faces)}\n')
            for face in faces:
                f.write(face.flag+'\n'+face.mat+'\nrefs 3\n')
                for j,u,v in face.refs:f.write(f'{j} {u:.7f} {v:.7f}\n')
            f.write('\n'.join(self.suffix)+'\n')


def area_xz(a,b,c):
    return abs((b[0]-a[0])*(c[2]-a[2])-(c[0]-a[0])*(b[2]-a[2]))*.5


def length_xz(a,b):
    return math.hypot(b[0]-a[0],b[2]-a[2])


def subdivide(tri,max_edge,depth):
    # tri = [(xyz,uv),..], linear UV interpolation.
    lengths=[length_xz(tri[i][0],tri[(i+1)%3][0]) for i in range(3)]
    if max(lengths)<=max_edge or depth<=0:
        yield tri;return
    j=lengths.index(max(lengths)); k=(j+1)%3; l=(j+2)%3
    a,b,c=tri[j],tri[k],tri[l]
    mid=(tuple((a[0][q]+b[0][q])/2 for q in range(3)),
         tuple((a[1][q]+b[1][q])/2 for q in range(2)))
    yield from subdivide([a,mid,c],max_edge,depth-1)
    yield from subdivide([mid,b,c],max_edge,depth-1)


def classify(ac, args):
    ys=[v[1] for v in ac.vertices]
    floor=min(ys)
    candidates=[]
    total_area=0.0
    for index,face in enumerate(ac.faces):
        a,b,c=[ac.vertices[j] for j,_,_ in face.refs]
        ar=area_xz(a,b,c)
        if ar<args.min_area:continue
        span=max(a[1],b[1],c[1])-min(a[1],b[1],c[1])
        max_edge=max(length_xz(a,b),length_xz(b,c),length_xz(c,a))
        if span/max(max_edge,1e-9)>args.max_slope:continue
        if max(a[1],b[1],c[1])>floor+args.floor_band:continue
        candidates.append(index);total_area+=ar
    return floor,candidates,total_area


def drape(ac,p,sampler,args,preview_only=True):
    floor,candidates,area=classify(ac,args)
    report={'model':str(ac.path),'placement':str(p.stg)+':'+str(p.line_index+1),
            'floor_y':round(floor,3),'candidate_faces':len(candidates),
            'candidate_area_m2':round(area,1),'total_faces':len(ac.faces),
            'status':'preview','corrected_faces':0,'skipped_missing_btg':0,
            'skipped_large_correction':0,'max_abs_correction_m':0.,'new_faces':0}
    if not candidates:return report,None
    anchor=sampler.query(p.lon,p.lat)
    if anchor is None:raise ValueError('BTG absent au point d ancrage')
    anchor_msl=p.altitude if p.keyword=='OBJECT_STATIC' else anchor.altitude+p.altitude
    cset=set(candidates)
    out_vertices=list(ac.vertices) if not preview_only else None
    out_faces=[] if not preview_only else None
    generated=0
    cache={}
    def terrain(xyz):
        key=(round(xyz[0],4),round(xyz[2],4))
        if key not in cache:
            lon,lat=vertex_geodetic(p,xyz)
            hit=sampler.query(lon,lat)
            cache[key]=hit.altitude if hit else None
        return cache[key]
    for idx,face in enumerate(ac.faces):
        if idx not in cset:
            if not preview_only:out_faces.append(face)
            continue
        tri=[(ac.vertices[j],(u,v)) for j,u,v in face.refs]
        fragments=list(subdivide(tri,args.max_edge,args.max_depth))
        if generated+len(fragments)>args.max_extra_faces:
            raise ValueError('Budget de subdivision depasse; reduire --max-depth ou augmenter --max-edge')
        proposed=[];deltas=[]
        for frag in fragments:
            piece=[]
            for xyz,uv in frag:
                altitude=terrain(xyz)
                if altitude is None:
                    piece=None;break
                new_y=altitude-anchor_msl+args.clearance
                deltas.append(new_y-xyz[1])
                piece.append(((xyz[0],new_y,xyz[2]),uv))
            if piece is None:break
            proposed.append(piece)
        if len(proposed)!=len(fragments):
            report['skipped_missing_btg']+=1
            if not preview_only:out_faces.append(face)
            continue
        largest=max(abs(v) for v in deltas)
        report['max_abs_correction_m']=max(report['max_abs_correction_m'],largest)
        if largest>args.max_correction:
            report['skipped_large_correction']+=1
            if not preview_only:out_faces.append(face)
            continue
        report['corrected_faces']+=1
        generated+=len(proposed)
        if not preview_only:
            for frag in proposed:
                refs=[]
                for xyz,uv in frag:
                    j=len(out_vertices)
                    out_vertices.append(xyz)
                    refs.append((j,*uv))
                out_faces.append(Face(face.flag,face.mat,refs))
    report['new_faces']=generated
    report['max_abs_correction_m']=round(report['max_abs_correction_m'],3)
    if not preview_only:report['status']='generated'
    return report,(out_vertices,out_faces) if not preview_only else None


def restore(root):
    manifest=root/'drape-v0310-manifest.json'
    if not manifest.exists():raise ValueError('Aucune sauvegarde v0.3.10')
    data=json.loads(manifest.read_text())
    stg=Path(data['stg']);backup=Path(data['backup']);clone=Path(data['clone'])
    if not (stg.exists() and backup.exists()):raise ValueError('STG ou sauvegarde manquante')
    # Do not overwrite later manual modifications.
    current=stg.read_text();lines=current.splitlines()
    if data['modified_line'] not in lines:raise ValueError('La ligne STG a change, restauration automatique refusee')
    shutil.copy2(backup,stg)
    if clone.exists():clone.unlink()
    manifest.unlink()
    print('STG restaure; original AC3D inchange')


def main():
    ap=argparse.ArgumentParser(description='XPlane2FlightGear v0.3.10: selective AC3D ground triangles draping, preview by default')
    ap.add_argument('--scenery',type=Path,default=Path.home()/'Desktop/TestAirport')
    ap.add_argument('--model',help='Name of converted AC3D model, e.g. c9acd550b541.ac')
    ap.add_argument('--scan',action='store_true',help='List large models and ground-like face counts without accessing BTG')
    ap.add_argument('--placement-index',type=int,default=0,help='0-based placement if model occurs more than once')
    ap.add_argument('--apply',action='store_true',help='Create per-placement AC3D clone and update one STG line')
    ap.add_argument('--restore',action='store_true')
    ap.add_argument('--floor-band',type=float,default=0.7,help='Candidate triangles within this height of model lowest point, metres')
    ap.add_argument('--min-area',type=float,default=2.,help='Minimum ground-like triangle horizontal area, m2')
    ap.add_argument('--max-slope',type=float,default=.08,help='Max vertical span / max horizontal edge')
    ap.add_argument('--max-edge',type=float,default=20.,help='Max new triangle edge before subdivision, metres')
    ap.add_argument('--max-depth',type=int,default=9)
    ap.add_argument('--max-extra-faces',type=int,default=100000)
    ap.add_argument('--max-correction',type=float,default=5.,help='Skip a face if any vertex requires larger vertical correction')
    ap.add_argument('--clearance',type=float,default=.05)
    args=ap.parse_args()
    root=args.scenery.expanduser().resolve()
    if args.restore:return restore(root)
    if args.scan:
        ps=placements(root)
        models={}
        for p in ps:
            path=p.stg.parent/p.model
            if path in models:models[path]['placements']+=1;continue
            if not path.is_file():continue
            try:
                ac=AC(path)
                floor,candidates,area=classify(ac,args)
                xs=[v[0] for v in ac.vertices];zs=[v[2] for v in ac.vertices]
                models[path]={'model':path.name,'placements':1,'triangles':len(ac.faces),
                              'size_x':round(max(xs)-min(xs),1),'size_z':round(max(zs)-min(zs),1),
                              'candidate_faces':len(candidates),'candidate_area_m2':round(area,1)}
            except (OSError,ValueError,IndexError) as exc:
                print(f'IGNORE {path.name}: {exc}')
        ranked=sorted(models.values(),key=lambda v:v['candidate_area_m2'],reverse=True)
        out=root/'drape-v0310-scan.json'
        out.write_text(json.dumps(ranked,indent=2,ensure_ascii=False),encoding='utf8')
        for m in ranked[:30]:print(f"{m['model']}  surface={m['candidate_area_m2']:.0f} m2 faces={m['candidate_faces']} dimension={m['size_x']}x{m['size_z']} m instances={m['placements']}")
        print('Scan:',out)
        return
    if not args.model:ap.error('--model requis (pas de correction automatique de toute la scene)')
    if Path(args.model).name!=args.model:ap.error('--model doit etre un simple nom de fichier AC3D')
    matches=[p for p in placements(root) if Path(p.model).name==args.model]
    if not matches:ap.error(f'Aucun placement actif pour {args.model}. Verifier les STG restaures.')
    if args.placement_index<0 or args.placement_index>=len(matches):ap.error(f'--placement-index hors limites: {len(matches)} placements')
    p=matches[args.placement_index];model=p.stg.parent/p.model
    if not model.is_file():ap.error(f'Modele absent: {model}')
    manifest=root/'drape-v0310-manifest.json'
    if args.apply and manifest.exists():ap.error('Une correction est deja active. Restaurer avant nouvel essai.')
    ac=AC(model)
    frame=(p.lon,p.lat)
    sampler=TerrainSampler(root/'Terrain',frame,margin=1000)
    # Bounds must cover whole model, not only its anchor.
    lo=[min(v[i] for v in ac.vertices) for i in (0,2)]
    hi=[max(v[i] for v in ac.vertices) for i in (0,2)]
    corners=[vertex_geodetic(p,(x,0,z)) for x in (lo[0],hi[0]) for z in (lo[1],hi[1])]
    sampler.load(corners+[frame])
    report,geometry=drape(ac,p,sampler,args,preview_only=not args.apply)
    report.update({'version':VERSION,'anchor':{'lon':p.lon,'lat':p.lat,'heading':p.heading,'height':p.altitude,'mode':p.keyword},'terrain_triangles':sampler.triangle_count,'warnings':sampler.errors,'placement_count_for_model':len(matches)})
    if args.apply:
        if sampler.errors:ap.error('Erreur BTG: correction refusee')
        if not report['corrected_faces']:ap.error('Aucune surface eligible; application refusee')
        clone=model.with_name(model.stem+f'.draped-{args.placement_index}.ac')
        backup=Path(str(p.stg)+'.pre-drape-v0310')
        if clone.exists() or backup.exists():ap.error('Sortie/sauvegarde deja presente; pas d ecrasement')
        verts,faces=geometry
        ac.write(clone,verts,faces)
        lines=p.stg.read_text().splitlines()
        parts=lines[p.line_index].split();parts[1]=clone.name
        modified_line=' '.join(parts)
        backup.write_text(p.stg.read_text(),encoding='utf8')
        lines[p.line_index]=modified_line
        p.stg.write_text('\n'.join(lines)+'\n',encoding='utf8')
        manifest.write_text(json.dumps({'stg':str(p.stg),'backup':str(backup),'clone':str(clone),'modified_line':modified_line},indent=2))
        report['modified_stg']=str(p.stg);report['clone']=str(clone)
    out=root/'drape-v0310-report.json'
    out.write_text(json.dumps(report,indent=2,ensure_ascii=False),encoding='utf8')
    print(json.dumps(report,ensure_ascii=False,indent=2))
    print(f'Rapport: {out}')

if __name__=='__main__':main()
